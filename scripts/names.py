TRANSLATIONS = dict(line.split("|", 1) for line in TERMS.strip().splitlines())
PATTERN = re.compile("|".join(re.escape(key) for key in sorted(TRANSLATIONS, key=len, reverse=True)))


def english_filename(name, identity, collision=False):
    if re.fullmatch(r"[A-Za-z0-9_.-]{1,180}", name) and not collision:
        return name, ""
    name = name.replace("р", "p")
    normalized = unicodedata.normalize("NFKC", name)
    # 先匹配原始全角标点，再匹配归一化文本，避免中文括号破坏完整短语。
    translated = PATTERN.sub(lambda match: "-" + TRANSLATIONS[match[0]] + "-", name)
    translated = unicodedata.normalize("NFKC", translated)
    translated = PATTERN.sub(lambda match: "-" + TRANSLATIONS[match[0]] + "-", translated)
    remaining = "".join(re.findall(r"[\u3400-\u9fff]+", translated))
    suffix = PurePosixPath(normalized).suffix
    if not suffix.isascii() or len(suffix) > 12:
        suffix = ""
    stem = translated[:-len(suffix)] if suffix else translated
    stem = re.sub(r"[^A-Za-z0-9._-]+", "-", stem)
    stem = re.sub(r"-+", "-", stem).strip("-.")[:150] or "file"
    if remaining or collision:
        stem += "-" + identity[:10]
    return stem + suffix, remaining
